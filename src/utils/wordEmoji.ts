/**
 * Normalizes text for matching:
 * lowercases, removes punctuation, replaces Turkish characters with ASCII for resilient stem matching.
 */
function normalizeForMatch(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .trim()
    .replace(/^to\s+/, '') // remove leading "to "
    .replace(/^[a-z]\s+/, '')
    .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'’]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function toAscii(text: string): string {
  return text
    .replace(/ğ/g, 'g')
    .replace(/ü/g, 'u')
    .replace(/ş/g, 's')
    .replace(/ı/g, 'i')
    .replace(/ö/g, 'o')
    .replace(/ç/g, 'c');
}

/**
 * Deduplicates and formats Turkish correct answer string.
 * Example: "yaşlanma, yaşlanma" -> "yaşlanma"
 */
export function formatCorrectAnswer(tr: string): string {
  if (!tr) return '';
  const parts = tr.split(/[,;\/]+/).map(s => s.trim()).filter(Boolean);
  if (parts.length <= 1) return tr;

  const seen = new Set<string>();
  const unique: string[] = [];

  for (const part of parts) {
    const key = part.toLowerCase();
    if (!seen.has(key)) {
      seen.add(key);
      unique.push(part);
    }
  }

  return unique.join(', ');
}

