/**
 * Finds a highly relevant emoji for a given word.
 * Returns null if no confident/relevant emoji is found (ensures no random nonsense).
 */
export function getWordEmoji(
  word: (Word | { en: string; tr: string; categories?: string[]; emoji?: string }) | null | undefined
): string | null {
  if (!word) return null;

  // Step 0: User-defined custom emoji(s) ALWAYS take highest priority!
  if (word.emoji && word.emoji.trim()) {
    return word.emoji.trim();
  }

  // Step 1: Normalize English
  const enNorm = normalizeForMatch(word.en);
  const enSimple = enNorm.replace(/\s+/g, '');

  if (EXACT_EN_MAP[enNorm]) return EXACT_EN_MAP[enNorm];
  if (EXACT_EN_MAP[enSimple]) return EXACT_EN_MAP[enSimple];

  // Try checking English single tokens
  const enTokens = enNorm.split(' ');
  for (const token of enTokens) {
    if (EXACT_EN_MAP[token]) {
      return EXACT_EN_MAP[token];
    }
    // Also try base form (strip -ing, -ed, -s)
    if (token.endsWith('ing') && EXACT_EN_MAP[token.slice(0, -3)]) {
      return EXACT_EN_MAP[token.slice(0, -3)];
    }
    if (token.endsWith('ed') && EXACT_EN_MAP[token.slice(0, -2)]) {
      return EXACT_EN_MAP[token.slice(0, -2)];
    }
    if (token.endsWith('s') && EXACT_EN_MAP[token.slice(0, -1)]) {
      return EXACT_EN_MAP[token.slice(0, -1)];
    }
  }

  // Step 2: Match Turkish translation (extremely effective for custom & synonyms)
  const trAscii = toAscii(word.tr.toLowerCase());

  for (const item of TR_KEYWORD_MAP) {
    if (item.pattern.test(trAscii)) {
      return item.emoji;
    }
  }

  // Step 3: Match against Word Categories if specific
  if (word.categories && word.categories.length > 0) {
    if (word.categories.includes('animals')) return '🐾';
    if (word.categories.includes('food')) return '🍽️';
    if (word.categories.includes('clothing')) return '👕';
    if (word.categories.includes('money')) return '💰';
    if (word.categories.includes('military_weapons')) return '⚔️';
    if (word.categories.includes('music')) return '🎵';
    if (word.categories.includes('space')) return '🚀';
    if (word.categories.includes('weather')) return '⛅';
    if (word.categories.includes('travel')) return '✈️';
  }

  return null;
}
